/**
 * 贝壳 API 使用策略 —— 集中定义调用预算，避免限流。
 *
 * ============================================================================
 * 为什么要集中定义（真实事故）
 * ============================================================================
 * 一次用户点击「AI 识别需求并匹配房源」原本会产生约 11 次贝壳调用：
 *   搜索 1 次 + 详情补全 Top5 × 2 次（detail + material）
 *
 * 加上失败重试，密集发出会触发贝壳限流 →
 * **所有工具返回 `service temporarily unavailable`** →
 * 连原本正常的搜索也被熔断挡住，且恢复需要很长时间
 * （实测 20+ 分钟仍未恢复）。
 *
 * 而实际上：经纪人**并不会每套都点开看详情**。
 * 为 5 套房源预取全部详情，其中大多数根本不会被查看 ——
 * 这是纯粹的浪费，而且换来了限流风险。
 *
 * ============================================================================
 * 策略调整（本文件定义的规则）
 * ============================================================================
 *   1. **搜索时只取摘要**（1 次调用）—— 推荐列表只需要摘要字段
 *   2. **详情按需加载** —— 经纪人点开某套时才取它的详情与图片
 *   3. **预算上限** —— 一次搜索最多 N 次调用，超出即降级到缓存
 *
 * 效果：一次搜索从 11 次调用降到 **1-4 次**（取决于经纪人点开几套）。
 */

export const BEIKE_USAGE_POLICY = {
  /**
   * 一次搜索允许的**详情调用**上限（每个房源 2 次：detail + material）。
   *
   * ============================================================================
   * 取值权衡（这里走过一次弯路，记录清楚避免再犯）
   * ============================================================================
   * 最初**不限制**（Top N 每套都取）→ 一次搜索 11-15 次调用 → 触发限流。
   * 然后我一度改成"默认不预取、完全按需"→ 但这**违背产品目标**：
   * 用户要的是"在平台上直接看到完整房源信息"，而不是点一下再去别处看。
   *
   * 正确解法不是"少取数据"，而是**"同样的数据只取一次"**：
   *   · 详情缓存 30 分钟 —— 同一房源在多次搜索中**只请求一次**
   *   · 节流器 400ms 间隔 —— 把突发摊平，不触发限流
   *   · 此预算 —— 兜住最坏情况（大量全新房源）
   *
   * 因此这里设 20（= 10 套房源，单次最多约 21 次调用）：
   *   · 好于"不预取"：用户能直接看到完整信息
   *   · 差于"无限制"：不会因为一次搜索打满配额
   *   · 配合缓存，**重复搜索几乎不再消耗配额**
   */
  prefetchDetailBudget: 20,

  /**
   * 节流器基础间隔（毫秒）。
   *
   * 400ms 依据：正常调用耗时 2-6 秒，400ms 间隔对总耗时影响很小，
   * 但能显著压平突发。
   */
  minCallIntervalMs: 400,

  /**
   * 节流器最大间隔（连续失败退避上限）。
   *
   * 2000ms 依据：连续失败说明服务端有压力，此时**宁可慢也要稳**；
   * 但不设更长是因为超过 2 秒会让正常恢复后的体验明显变差。
   */
  maxCallIntervalMs: 2000,

  /**
   * 限流熔断的冷却时长（毫秒）。
   *
   * ⚠️ 这个值从 120 秒**大幅延长**是刻意的：
   * 实测贝壳限流恢复需要**20 分钟以上**，而原先的 120 秒冷却结束后
   * 会立刻再试 → 再次失败 → 再等 120 秒 → 反复触发，
   * 既拿不到数据，又可能延长限流窗口。
   *
   * 5 分钟是折中：足够让服务端压力缓解，又不至于恢复后等太久。
   */
  throttleCooldownMs: 5 * 60_000,

  /**
   * 详情缓存 TTL（毫秒）—— 30 分钟。
   *
   * 房源详情变化很慢（小区容积率/绿化率几乎不变，价格以天计），
   * 缓存 30 分钟既省调用又不影响准确性。
   */
  detailCacheTtlMs: 30 * 60_000,
} as const;

/**
 * 判断错误是否为「贝壳限流」。
 *
 * 特征（实测）：
 *   · 错误文本含 `service temporarily unavailable`
 *   · 响应**极快**（约 220ms）—— 与服务端真正处理请求的 2-6 秒形成对比
 *
 * 为什么要专门判定：限流时**重试会让情况更糟**，
 * 必须与"网络抖动"区分开 —— 后者重试是有意义的。
 */
export function isThrottledError(error: unknown): boolean {
  const text =
    error instanceof Error
      ? `${error.message} ${String((error as { stderr?: unknown }).stderr ?? '')}`
      : String(error);

  return /service\s+temporarily\s+unavailable/i.test(text) || /CIRCUIT_OPEN/.test(text);
}
